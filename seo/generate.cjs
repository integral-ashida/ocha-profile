/**
 * Search-indexable species pages for ocha-profile.
 * Uses existing templates, CSS, media, and species data without modifying them.
 * Run: node seo/generate.cjs
 */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ROOT = path.resolve(__dirname, '..');
const SITE = 'https://integral-ashida.github.io/ocha-profile/';
const read = rel => fs.readFileSync(path.join(ROOT, rel), 'utf8');
const write = (rel, body) => {
  const dest = path.join(ROOT, rel);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, body, 'utf8');
};
const esc = value => String(value ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;')
  .replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');
const attr = esc;
const data = read('js/species-data.js');
const context = vm.createContext(Object.create(null));
const species = vm.runInContext(`${data}\nSPECIES`, context, {timeout: 1500});
if (!Array.isArray(species) || !species.length) throw new Error('SPECIES was not found.');
const template = read('species.html');
const script = read('js/species.js');
const oldSelect = "params.get('id')";
if (!script.includes(oldSelect)) throw new Error('species.js species selection changed; revise generator before deployment.');
const seoScript = script.replace(oldSelect, `(params.get('id') || document.documentElement.dataset.speciesId)`);
write('js/species-seo.js', '// Automatically generated. Do not edit.\n' + seoScript);
const oldTag = /<script\s+src=["']js\/species\.js["']><\/script>/;
if (!oldTag.test(template)) throw new Error('species.html no longer loads js/species.js as expected.');
const ids = new Set();
for (const item of species) {
  if (!item.id || !/^[a-z0-9-]+$/.test(item.id)) throw new Error(`Unsafe species ID: ${item.id}`);
  if (ids.has(item.id)) throw new Error(`Duplicate species ID: ${item.id}`);
  ids.add(item.id);
  const file = `species-${item.id}.html`;
  const url = SITE + file;
  const name = String(item.name || '');
  const latin = String(item.latin || '');
  const facts = [item.bodyLength && `体長：${item.bodyLength}`, item.habitat && `分布：${item.habitat}`].filter(Boolean);
  const summary = `${name}${latin ? `（${latin}）` : ''}の標本写真、特徴、${facts.join('、')}を紹介。日本の主なゲンゴロウ。`;
  let html = template;
  html = html.replace(/<html\b([^>]*)>/, (_, tail) => `<html${tail} data-species-id="${attr(item.id)}">`);
  html = html.replace(/<title>[^<]*<\/title>/, `<title>${esc(name)}${latin ? `（${esc(latin)}）` : ''}｜日本の主なゲンゴロウ</title>`);
  html = html.replace(/<meta\s+name=["']description["']\s+content=["'][^"']*["']\s*\/?\s*>/,
    `<meta name="description" content="${attr(summary)}">`);
  const headAddon = `\n<link rel="canonical" href="${attr(url)}">\n<meta property="og:type" content="article">\n<meta property="og:title" content="${attr(name)}｜日本の主なゲンゴロウ">\n<meta property="og:description" content="${attr(summary)}">\n<meta property="og:url" content="${attr(url)}">\n`;
  html = html.replace('</head>', headAddon + '</head>');
  html = html.replace('<h1 id="species-name"></h1>', `<h1 id="species-name">${esc(name)}</h1>`);
  html = html.replace('<p id="species-latin" class="latin"></p>', `<p id="species-latin" class="latin"${latin ? '' : ' hidden'}>${esc(latin)}</p>`);
  html = html.replace('<img id="species-hero" src="" alt="">', `<img id="species-hero" src="${attr(item.image || '')}" alt="${attr(name)}">`);
  html = html.replace('<p id="species-description"></p>', `<p id="species-description">${esc(item.description || '編集中、もうしばらくお待ちください')}</p>`);
  // Match the same facts DOM that species.js inserts on the client, for no-JS readers/crawlers.
  // Client JS removes this node and regenerates the identical one.
  const displayFacts = [['大きさ',item.bodyLength],['生息地',item.habitat],['環境省カテゴリー',item.redList]]
    .filter(([,v]) => typeof v === 'string' && v.trim());
  if (displayFacts.length) {
    const section = `<section id="species-facts" class="species-facts" aria-label="基本情報"><dl>${displayFacts.map(([k,v]) => `<div class="species-facts-row"><dt>${esc(k)}</dt><dd>${esc(v.trim())}</dd></div>`).join('')}</dl></section>`;
    html = html.replace('</figure><section class="species-description">', `</figure>${section}<section class="species-description">`);
  }
  html = html.replace('<nav id="species-index-list" class="species-index-list" aria-label="種一覧"></nav>',
    `<nav id="species-index-list" class="species-index-list" aria-label="種一覧">${species.map(s => `<a href="species-${attr(s.id)}.html"${s.id === item.id ? ' class="current"' : ''}>${esc(s.name)}</a>`).join('')}</nav>`);
  html = html.replace(oldTag, '<script src="js/species-seo.js"></script>');
  write(file, '<!-- Generated by seo/generate.cjs; do not edit directly. -->\n' + html + '\n');
}
const xmlEsc = esc;
const urls = ['db.html', ...species.map(s => `species-${s.id}.html`)];
write('sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.map(u => `  <url><loc>${xmlEsc(SITE + u)}</loc></url>`).join('\n')}\n</urlset>\n`);
// The public catalog can retain legacy URLs without harming visitors. For Google,
// sitemap + links on generated pages provide discovery paths.
console.log(`Generated ${species.length} static species pages, species-seo.js, and sitemap.xml.`);
